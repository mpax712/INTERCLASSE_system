BEGIN;

CREATE TABLE IF NOT EXISTS classes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_classes_name ON classes (name);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    email varchar(160) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'representante'
        CHECK (role IN ('admin', 'professor', 'representante')),
    class_id integer REFERENCES classes(id) ON DELETE SET NULL,
    representative_gender varchar(20)
        CHECK (representative_gender IN ('masculino', 'feminino')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_users_email ON users (lower(email));
CREATE INDEX IF NOT EXISTS idx_users_class_id ON users (class_id);

CREATE TABLE IF NOT EXISTS user_modalities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, modality)
);
CREATE INDEX IF NOT EXISTS idx_user_modalities_user ON user_modalities (user_id);
CREATE INDEX IF NOT EXISTS idx_user_modalities_modality ON user_modalities (modality);

CREATE TABLE IF NOT EXISTS events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(160) NOT NULL,
    description text,
    created_by integer NOT NULL REFERENCES users(id),
    start_date date NOT NULL,
    end_date date,
    place varchar(160),
    status varchar(30) NOT NULL DEFAULT 'rascunho'
        CHECK (status IN ('rascunho', 'inscricoes', 'em_andamento', 'encerrado')),
    group_count integer NOT NULL DEFAULT 2,
    best_thirds_count integer NOT NULL DEFAULT 0,
    teams_advancing_per_group integer NOT NULL DEFAULT 2,
    advancement_mode varchar(20) NOT NULL DEFAULT 'global'
        CHECK (advancement_mode IN ('global', 'per_group')),
    roster_edit_until timestamp,
    archived smallint NOT NULL DEFAULT 0 CHECK (archived IN (0, 1)),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_events_created_by ON events (created_by);
CREATE INDEX IF NOT EXISTS idx_events_status_start ON events (status, start_date);
CREATE INDEX IF NOT EXISTS idx_events_archived ON events (archived);

CREATE TABLE IF NOT EXISTS event_modalities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    score_type varchar(20) NOT NULL,
    set_best_of integer,
    set_points integer,
    quarters_count integer,
    max_players_per_team integer,
    bracket_type varchar(30) NOT NULL DEFAULT 'groups',
    rules_json jsonb,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (event_id, modality)
);

CREATE TABLE IF NOT EXISTS event_group_advancement (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    gender varchar(20) NOT NULL DEFAULT 'masculino',
    group_name varchar(10) NOT NULL,
    teams_advancing integer NOT NULL DEFAULT 0,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp,
    UNIQUE (event_id, modality, gender, group_name)
);
CREATE INDEX IF NOT EXISTS idx_event_group_advancement_event ON event_group_advancement (event_id);

CREATE TABLE IF NOT EXISTS teams (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    name varchar(120) NOT NULL,
    class_name varchar(80),
    gender varchar(20) DEFAULT 'masculino',
    group_name varchar(10) NOT NULL DEFAULT 'A',
    representative_id integer REFERENCES users(id) ON DELETE SET NULL,
    representative_name varchar(160),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_teams_event_modality ON teams (event_id, modality, group_name);
CREATE INDEX IF NOT EXISTS idx_teams_gender ON teams (gender);
CREATE INDEX IF NOT EXISTS idx_teams_representative_id ON teams (representative_id);

CREATE TABLE IF NOT EXISTS players (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    name varchar(120) NOT NULL,
    email varchar(160),
    birth_date date,
    jersey_number integer,
    group_name varchar(10),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_players_team_id ON players (team_id);
CREATE INDEX IF NOT EXISTS idx_players_user_id ON players (user_id);
CREATE INDEX IF NOT EXISTS idx_players_email ON players (email);

CREATE TABLE IF NOT EXISTS matches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    stage varchar(30) NOT NULL DEFAULT 'grupo',
    group_name varchar(10),
    home_team_id integer REFERENCES teams(id) ON DELETE SET NULL,
    away_team_id integer REFERENCES teams(id) ON DELETE SET NULL,
    home_score integer NOT NULL DEFAULT 0,
    away_score integer NOT NULL DEFAULT 0,
    score_data jsonb,
    gender varchar(20) DEFAULT 'masculino',
    status varchar(30) NOT NULL DEFAULT 'agendada',
    starts_at timestamp,
    place varchar(160),
    winner_team_id integer REFERENCES teams(id) ON DELETE SET NULL,
    home_player_id integer REFERENCES players(id) ON DELETE SET NULL,
    away_player_id integer REFERENCES players(id) ON DELETE SET NULL,
    winner_player_id integer REFERENCES players(id) ON DELETE SET NULL,
    home_source_match_id integer REFERENCES matches(id) ON DELETE SET NULL,
    away_source_match_id integer REFERENCES matches(id) ON DELETE SET NULL,
    rules_snapshot jsonb,
    version integer NOT NULL DEFAULT 0,
    cancel_reason varchar(240),
    cancelled_by integer REFERENCES users(id) ON DELETE SET NULL,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_matches_public ON matches (event_id, modality, starts_at, status);
CREATE INDEX IF NOT EXISTS idx_matches_gender_stage ON matches (event_id, modality, gender, stage);
CREATE INDEX IF NOT EXISTS idx_matches_home_team_id ON matches (home_team_id);
CREATE INDEX IF NOT EXISTS idx_matches_away_team_id ON matches (away_team_id);
CREATE INDEX IF NOT EXISTS idx_matches_winner_team_id ON matches (winner_team_id);
CREATE INDEX IF NOT EXISTS idx_matches_player_home ON matches (home_player_id);
CREATE INDEX IF NOT EXISTS idx_matches_player_away ON matches (away_player_id);
CREATE INDEX IF NOT EXISTS idx_matches_source_home ON matches (home_source_match_id);
CREATE INDEX IF NOT EXISTS idx_matches_source_away ON matches (away_source_match_id);
CREATE INDEX IF NOT EXISTS idx_matches_event_filters ON matches (event_id, modality, gender, stage, status, starts_at, id);

CREATE TABLE IF NOT EXISTS score_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    action varchar(120) NOT NULL,
    description varchar(255),
    old_home_score integer,
    old_away_score integer,
    new_home_score integer,
    new_away_score integer,
    old_status varchar(40),
    new_status varchar(40),
    old_score_data jsonb,
    new_score_data jsonb,
    request_id varchar(64),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_score_logs_match_id ON score_logs (match_id);
CREATE INDEX IF NOT EXISTS idx_score_logs_user_id ON score_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_score_logs_created_at ON score_logs (created_at);
CREATE UNIQUE INDEX IF NOT EXISTS uniq_score_logs_request ON score_logs (match_id, request_id);

CREATE TABLE IF NOT EXISTS occurrences (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    team_id integer NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    player_id integer REFERENCES players(id) ON DELETE SET NULL,
    target_type varchar(20) NOT NULL CHECK (target_type IN ('player', 'team')),
    title varchar(160) NOT NULL,
    description text NOT NULL,
    action_text text,
    ineligible_next_game smallint NOT NULL DEFAULT 0 CHECK (ineligible_next_game IN (0, 1)),
    points_deducted integer NOT NULL DEFAULT 0,
    created_by integer REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_occurrences_event ON occurrences (event_id);
CREATE INDEX IF NOT EXISTS idx_occurrences_match ON occurrences (match_id);
CREATE INDEX IF NOT EXISTS idx_occurrences_team ON occurrences (team_id);
CREATE INDEX IF NOT EXISTS idx_occurrences_player ON occurrences (player_id);
CREATE INDEX IF NOT EXISTS idx_occurrences_created_by ON occurrences (created_by);

CREATE TABLE IF NOT EXISTS suggestions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer REFERENCES users(id) ON DELETE SET NULL,
    type varchar(20) NOT NULL DEFAULT 'melhoria'
        CHECK (type IN ('bug', 'melhoria', 'outro')),
    title varchar(160) NOT NULL,
    description text NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'nova'
        CHECK (status IN ('nova', 'em_analise', 'resolvida', 'arquivada')),
    admin_note text,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp
);
CREATE INDEX IF NOT EXISTS idx_suggestions_status ON suggestions (status);
CREATE INDEX IF NOT EXISTS idx_suggestions_user_id ON suggestions (user_id);

CREATE TABLE IF NOT EXISTS class_standings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    class_name varchar(120) NOT NULL,
    total_points integer NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (event_id, class_name)
);

CREATE TABLE IF NOT EXISTS class_modality_points (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_standings_id integer NOT NULL REFERENCES class_standings(id) ON DELETE CASCADE,
    modality varchar(40) NOT NULL,
    gender varchar(20) NOT NULL,
    position integer NOT NULL,
    points integer NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (class_standings_id, modality, gender)
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_event_group_advancement_updated_at ON event_group_advancement;
CREATE TRIGGER trg_event_group_advancement_updated_at
BEFORE UPDATE ON event_group_advancement
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_suggestions_updated_at ON suggestions;
CREATE TRIGGER trg_suggestions_updated_at
BEFORE UPDATE ON suggestions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_class_standings_updated_at ON class_standings;
CREATE TRIGGER trg_class_standings_updated_at
BEFORE UPDATE ON class_standings
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- O aplicativo acessa o banco exclusivamente pelo servidor PHP. Sem policies,
-- RLS bloqueia acesso direto pelas chaves anon/authenticated da API Supabase.
ALTER TABLE classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_modalities ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_modalities ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_group_advancement ENABLE ROW LEVEL SECURITY;
ALTER TABLE teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE score_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE occurrences ENABLE ROW LEVEL SECURITY;
ALTER TABLE suggestions ENABLE ROW LEVEL SECURITY;
ALTER TABLE class_standings ENABLE ROW LEVEL SECURITY;
ALTER TABLE class_modality_points ENABLE ROW LEVEL SECURITY;

COMMIT;
